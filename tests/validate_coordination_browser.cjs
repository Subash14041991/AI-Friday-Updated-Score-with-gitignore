const {launchBrowser}=require('../scripts/node_runtime.cjs');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const {createHash}=require('node:crypto');
const folder=path.resolve('poc/referral-coordination');
const checks=[];
(async()=>{
  const browser=await launchBrowser();
  try{
    const page=await browser.newPage({viewport:{width:1440,height:1050}}),errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    // Controlled wall clock verifies the real deadline logic without making
    // the browser suite wait a minute. The application has no time-advance UI.
    await page.clock.install({time:new Date('2026-10-08T05:00:00Z')});
    await page.goto(pathToFileURL(path.join(folder,'index.html')).href);
    assert.equal(await page.locator('.record').count(),0);
    checks.push('Empty workspace; no examples loaded automatically');
    await page.locator('#add').click();
    const editor=page.locator('#editor');
    await editor.locator('[name=id]').fill('LOCAL-001');
    await editor.locator('[name=receiver]').fill('Review provider');
    await editor.locator('[name=actor]').fill('Reviewer');
    await editor.getByRole('button',{name:'Save referral'}).click();
    const record=page.locator('.record').filter({has:page.getByRole('heading',{name:'LOCAL-001',exact:true})});
    assert.match(await record.innerText(),/Needs information/);
    assert.equal(await record.getByRole('button',{name:'Record hand-off',exact:true}).count(),0);
    checks.push('Incomplete record saved and hand-off blocked');
    await record.getByRole('button',{name:'Edit details'}).click();
    await editor.locator('[name=specialty]').fill('Cardiology');
    await editor.locator('[name=actor]').fill('Reviewer');
    await editor.getByRole('button',{name:'Save referral'}).click();
    assert.match(await record.innerText(),/Ready for hand-off/);
    checks.push('Correction revalidates record without creating a duplicate');
    await page.locator('#settings').click();
    const action=page.locator('#action');
    await action.locator('[name=minutes]').fill('1');
    await action.locator('[name=actor]').fill('Reviewer');
    await action.getByRole('button',{name:'Save',exact:true}).click();
    await record.getByRole('button',{name:'Record hand-off',exact:true}).click();
    assert.match(await action.innerText(),/sends no message/);
    assert.equal(await action.locator('[name=actor]').inputValue(),'');
    await action.locator('[name=actor]').fill('Reviewer');
    await action.getByRole('button',{name:'Save',exact:true}).click();
    assert.equal(await action.locator('[name=detail]').evaluate(el=>el.validity.valueMissing),true);
    assert.equal(await action.isVisible(),true);
    await action.locator('[name=detail]').fill('H-001');
    await action.getByRole('button',{name:'Save',exact:true}).click();
    assert.match(await record.innerText(),/Awaiting receipt/);
    checks.push('Recorded external hand-off requires reference and deliberate actor');
    await page.reload();
    assert.match(await record.innerText(),/Awaiting receipt/);
    assert.match(await page.locator('#history').innerText(),/H-001/);
    checks.push('Records and action history survive refresh');
    await page.clock.fastForward(61000);
    assert.match(await record.innerText(),/Follow-up overdue/);
    assert.equal(await record.locator('.tag.overdue').count(),1);
    checks.push('Deadline produces visible overdue state using wall-clock time (controlled test clock)');
    await record.getByRole('button',{name:'Approve retry'}).click();
    await action.locator('[name=actor]').fill('Reviewer');
    await action.locator('[name=detail]').fill('Receiving office contacted; another attempt approved');
    await action.getByRole('button',{name:'Approve retry',exact:true}).click();
    await record.getByRole('button',{name:'Record hand-off',exact:true}).click();
    await action.locator('[name=actor]').fill('Reviewer');
    await action.locator('[name=detail]').fill('H-002');
    await action.getByRole('button',{name:'Save',exact:true}).click();
    await record.getByRole('button',{name:'Record receipt'}).click();
    await action.locator('[name=actor]').fill('Reviewer');
    await action.locator('[name=detail]').fill('Partner confirmation ACK-002');
    await action.getByRole('button',{name:'Save',exact:true}).click();
    assert.match(await record.innerText(),/Receipt recorded/);
    assert.match(await record.innerText(),/Hand-off attempts\s*2/);
    assert.equal(await record.getByRole('button',{name:'Edit details'}).count(),0);
    checks.push('Approved retry, second hand-off, receipt reference and post-hand-off edit restriction');
    await page.locator('#examples').click();
    assert.equal(await page.locator('.record').count(),4);
    await page.locator('#examples').click();
    assert.equal(await page.locator('.record').count(),4);
    checks.push('Optional examples retain user record and never duplicate on reload');
    await page.locator('#search').fill('LOCAL-001');
    assert.equal(await page.locator('.record').count(),1);
    await page.locator('#search').fill('');
    await page.locator('#filter').selectOption('Receipt recorded');
    assert.equal(await page.locator('.record').count(),1);
    await page.locator('#filter').selectOption('');
    checks.push('Search and status filters');
    await page.screenshot({path:path.join(folder,'application-preview.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    assert.deepEqual(errors,[]);
    checks.push('Mobile layout without horizontal overflow; no browser errors');
    await page.setViewportSize({width:1440,height:1050});
    await page.locator('#reset').click();
    const reset=page.locator('#reset-dialog');
    assert.match(await reset.innerText(),/4 record/);
    await reset.getByRole('button',{name:'Cancel',exact:true}).click();
    assert.equal(await page.locator('.record').count(),4);
    await page.locator('#reset').click();
    await reset.locator('[name=confirmation]').fill('reset');
    await reset.getByRole('button',{name:'Reset permanently'}).click();
    assert.match(await page.locator('#reset-error').innerText(),/RESET/);
    assert.equal(await page.locator('.record').count(),4);
    checks.push('Reset cancellation and incorrect confirmation preserve records');
    const downloadEvent=page.waitForEvent('download');
    await page.locator('#reset-export').click();
    const download=await downloadEvent;
    const exported=JSON.parse(fs.readFileSync(await download.path(),'utf8'));
    assert.equal(exported.records.length,4);assert.ok(exported.events.length>0);assert.equal(exported.followUpMinutes,1);
    checks.push('Export from reset dialog contains current records, history and settings');
    await reset.locator('[name=confirmation]').fill('RESET');
    await page.screenshot({path:path.join(folder,'reset-preview.png')});
    await reset.getByRole('button',{name:'Reset permanently'}).click();
    assert.equal(await page.locator('.record').count(),0);
    assert.match(await page.locator('#history').innerText(),/No recorded actions/);
    assert.match(await page.locator('#saved').innerText(),/Follow-up 30 min/);
    await page.reload();assert.equal(await page.locator('.record').count(),0);
    assert.match(await page.locator('#history').innerText(),/No recorded actions/);
    await page.locator('#examples').click();assert.equal(await page.locator('.record').count(),3);
    assert.deepEqual(errors,[]);
    checks.push('Confirmed reset restores defaults, persists empty after refresh, and permits new entries');
    const artifactSha256={};for(const name of ['index.html','styles.css','config.js','workflow.js','app.js'])artifactSha256[name]=createHash('sha256').update(fs.readFileSync(path.join(folder,name))).digest('hex');
    fs.writeFileSync(path.join(folder,'browser-validation.json'),JSON.stringify({executedAt:new Date().toISOString(),passed:checks.length,checks,artifactSha256,scope:'Local browser workflow with a controlled test clock. No network integration, authenticated identity, clinical validation, or production audit.'},null,2)+'\n');
    console.log(`${checks.length} browser checks passed; application preview saved.`);
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
