// Exercise the actual browser artifact; capture current evidence without
// regenerating unrelated report pages or the full PDF.
const {launchBrowser}=require('../scripts/node_runtime.cjs');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {createHash} = require('node:crypto');
const {pathToFileURL} = require('node:url');
const folder = path.resolve(process.argv[2] || 'output/healthcare');
const evidencePath = path.resolve(process.argv[3] || '.review/d4-browser-validation.json');
const checks = [];
const record = (page, id) => page.locator('.record').filter({has:page.getByRole('heading',{name:id,exact:true})});
(async()=>{
  const browser = await launchBrowser();
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1000}});
    const errors=[]; page.on('pageerror',e=>errors.push(e.message));
    await page.goto(pathToFileURL(path.join(folder,'poc-referral-validation.html')).href);
    await page.locator('#validate').click();
    assert.equal(await page.locator('.record').count(),5);
    assert.equal(await page.locator('.state.follow-up').count(),3);
    checks.push('Five fictional referrals; three incomplete states visible');
    assert.equal(await record(page,'REF-SYN-002').getByRole('button',{name:'Simulate send',exact:true}).count(),0);
    checks.push('Incomplete referral has no send action');
    const first=record(page,'REF-SYN-001');
    await first.getByRole('button',{name:'Simulate send',exact:true}).click();
    assert.equal(await first.locator('.state.waiting').count(),1);
    await first.getByRole('button',{name:'Simulate partner receipt'}).click();
    assert.equal(await first.locator('.state.received').count(),1);
    assert.match(await first.innerText(),/Receipt is not completed care/);
    checks.push('Send and receipt states; receipt remains distinct from completion');
    const silent=record(page,'REF-SYN-005');
    await silent.getByRole('button',{name:'Simulate send',exact:true}).click();
    await page.locator('#advance').click();
    assert.equal(await silent.locator('.state.overdue').count(),1);
    assert.match(await silent.innerText(),/Responsible role: Coordinator/);
    checks.push('Simulated timeout visibly assigns coordinator follow-up');
    const expectRejected=async()=>{
      const dialog=new Promise(resolve=>page.once('dialog',async d=>{const message=d.message();await d.accept();resolve(message);}));
      await silent.getByRole('button',{name:'Approve retry'}).click();
      assert.match(await dialog,/reviewer and follow-up reason/);
      assert.match(await silent.innerText(),/Acknowledgement overdue/);
    };
    assert.equal(await silent.locator('[data-actor]').inputValue(),'');
    await expectRejected();
    await silent.locator('[data-actor]').fill('Demo reviewer');
    await expectRejected();
    await silent.locator('[data-actor]').fill('');
    await silent.locator('[data-reason]').fill('Mock partner contacted; safe retry approved');
    await expectRejected();
    checks.push('Blank reviewer or reason rejected without changing status');
    await silent.locator('[data-actor]').fill('Demo reviewer');
    await silent.getByRole('button',{name:'Approve retry'}).click();
    await silent.getByRole('button',{name:'Simulate send',exact:true}).click();
    await silent.getByRole('button',{name:'Simulate partner receipt'}).click();
    assert.match(await silent.innerText(),/send attempts: 2/);
    checks.push('Approved retry retains the referral and records second attempt');
    await page.locator('#duplicate').click();
    assert.equal(await page.locator('.record').count(),5);
    assert.match(await page.locator('#audit').innerText(),/Duplicate ignored/);
    checks.push('Replay retains five records and logs duplicate');
    assert.match(await page.locator('#audit').innerText(),/Demo reviewer.*Mock partner contacted/);
    checks.push('Action history includes reviewer and reason');
    await page.screenshot({path:path.join(path.dirname(evidencePath),'d4-poc-preview.png'),fullPage:true});
    await page.locator('#reset').click();
    assert.equal(await page.locator('.record').count(),0);
    assert.equal(await page.locator('#audit').innerText(),'No actions yet.');
    checks.push('Reset clears records and history');
    await page.setViewportSize({width:390,height:844});
    await page.locator('#validate').click();
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    assert.deepEqual(errors,[]);
    checks.push('Mobile layout has no horizontal overflow; no browser script errors');
    const hashes={};
    for(const name of ['poc-referral-validation.html','referral-workflow.js']) hashes[name]=createHash('sha256').update(fs.readFileSync(path.join(folder,name))).digest('hex');
    fs.writeFileSync(evidencePath,JSON.stringify({executedAt:new Date().toISOString(),result:'PASS',passed:checks.length,checks,artifactSha256:hashes,limits:'Scripted synthetic browser behavior only; no representative-user usability, authentication, clinical, real-interface, or production validation.'},null,2)+'\n');
    console.log(`${checks.length} browser checks passed; evidence: ${evidencePath}`);
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
